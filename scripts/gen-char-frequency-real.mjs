import fs from 'fs';
import path from 'path';
import https from 'https';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const CSV_URL = 'https://zhuyuhao.com/chinese-characters-frequency/tables/%E5%85%AD%E5%84%84%E7%9F%A5%E4%B9%8E%E8%AA%9E%E6%96%99%E9%80%9A%E8%A6%8F%E6%BC%A2%E5%AD%97%E5%AD%97%E9%A0%BB%E8%A1%A8.csv';

function fetchCSV(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve(data));
      res.on('error', reject);
    }).on('error', reject);
  });
}

async function main() {
  console.log('Fetching real frequency data from 六亿知乎语料通规汉字字频表...');
  let csvText;
  try {
    csvText = await fetchCSV(CSV_URL);
    console.log(`Downloaded ${csvText.length} bytes`);
  } catch (e) {
    console.error('Failed to fetch CSV, falling back to local data:', e.message);
    process.exit(1);
  }

  const lines = csvText.split(/\r?\n/).filter(l => l.trim());
  console.log(`CSV lines: ${lines.length}`);

  const header = lines[0];
  console.log(`Header: ${header}`);

  const freqMap = {};
  let freqSum = 0;
  const orderedChars = [];

  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].split(',');
    if (parts.length < 3) continue;
    const char = parts[0].trim();
    const count = parseInt(parts[1].trim());
    const freq = parseFloat(parts[2].trim());

    if (!char || char.length !== 1) continue;
    const cp = char.codePointAt(0);
    if (!((cp >= 0x4E00 && cp <= 0x9FFF) || (cp >= 0x3400 && cp <= 0x4DBF))) continue;

    freqMap[char] = freq;
    freqSum += freq;
    orderedChars.push(char);
  }

  console.log(`Parsed ${orderedChars.length} characters`);
  console.log(`Frequency sum: ${freqSum.toFixed(6)}`);

  const sumCheck = Object.values(freqMap).reduce((s, v) => s + v, 0);
  console.log(`Sum check: ${sumCheck.toFixed(6)}`);

  const outLines = [];
  outLines.push('// Auto-generated by scripts/gen-char-frequency-real.mjs');
  outLines.push('// DO NOT EDIT MANUALLY');
  outLines.push(`// Total chars: ${orderedChars.length}`);
  outLines.push('// Source: 六亿知乎语料通规汉字字频表');
  outLines.push('// URL: https://zhuyuhao.com/chinese-characters-frequency/');
  outLines.push('// Frequency values are normalized (sum ≈ 1.0)');
  outLines.push('');
  outLines.push('export const charFrequency: Record<string, number> = {');

  const entries = Object.entries(freqMap);
  for (let i = 0; i < entries.length; i++) {
    const [ch, freq] = entries[i];
    const comma = i < entries.length - 1 ? ',' : '';
    outLines.push(`  '${ch}': ${freq.toFixed(10)}${comma}`);
  }

  outLines.push('};');
  outLines.push('');
  outLines.push('export const charFreqOrder: string[] = [');
  for (let i = 0; i < orderedChars.length; i++) {
    const comma = i < orderedChars.length - 1 ? ',' : '';
    outLines.push(`  '${orderedChars[i]}'${comma}`);
  }
  outLines.push('];');
  outLines.push('');

  const output = outLines.join('\n');
  const outPath = path.join(rootDir, 'src', 'data', 'charFrequency.ts');
  fs.writeFileSync(outPath, output, 'utf8');
  console.log(`Written to ${outPath}`);
  console.log(`File size: ${(Buffer.byteLength(output, 'utf8') / 1024).toFixed(1)} KB`);
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
