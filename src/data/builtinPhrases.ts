/** 随机获取指定数量的词组 */
export function getRandomPhrases(count: number): string[] {
  if (count <= 0) return [];
  const shuffled = [...phraseList].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

/** 按长度获取词组 */
export function getPhrasesByLength(length: number): string[] {
  if (length <= 0) return [];
  return phraseList.filter(p => p.length === length);
}

