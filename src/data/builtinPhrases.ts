/** 检查字符串是否只包含汉字 */
function isAllHan(str: string): boolean {
  for (const ch of str) {
    const code = ch.charCodeAt(0);
    const cp = ch.codePointAt(0) ?? 0;
    const isHan = (code >= 0x4E00 && code <= 0x9FFF) ||
                  (code >= 0x3400 && code <= 0x4DBF) ||
                  (cp >= 0x20000 && cp <= 0x2A6DF);
    if (!isHan) return false;
  }
  return true;
}

/** 清理词组列表：过滤非汉字、去重 */
function cleanPhrases(phrases: string[], name: string): string[] {
  const validPhrases = phrases.filter(p => {
    if (!p || p.length < 2) return false;
    if (!isAllHan(p)) {
      console.warn(`[builtinPhrases] 过滤非汉字词组[${name}]: "${p}"`);
      return false;
    }
    return true;
  });

  const seen = new Set<string>();
  const unique: string[] = [];
  for (const p of validPhrases) {
    if (!seen.has(p)) {
      seen.add(p);
      unique.push(p);
    }
  }

  if (unique.length !== validPhrases.length) {
    console.warn(`[builtinPhrases] 词组集[${name}]去除了 ${validPhrases.length - unique.length} 个重复项`);
  }

  return unique;
}

