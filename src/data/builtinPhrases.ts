// 获取指定数量的词组
export function getPhrases(count: number = 10000): string[] {
  const allPhrases: string[] = [
    ...commonTwoCharWords,
    ...commonThreeCharWords,
    ...commonIdioms,
  ];
  
  if (count >= allPhrases.length) {
    return allPhrases;
  }
  
  return allPhrases.slice(0, count);
}

// 检查词组中的字符是否都在码表中
export function checkPhraseInCodeTable(
  phrase: string,
  codeTableChars: Set<string>
): { valid: boolean; missingChars: string[] } {
  const chars = phrase.split('');
  const missingChars: string[] = [];
  
  for (const char of chars) {
    if (/[\u4e00-\u9fa5]/.test(char) && !codeTableChars.has(char)) {
      missingChars.push(char);
    }
  }
  
  return {
    valid: missingChars.length === 0,
    missingChars,
  };
}

// 批量检查词组
export function batchCheckPhrases(
  phrases: string[],
  codeTableChars: Set<string>
): { total: number; valid: number; invalid: number; invalidPhrases: Array<{ phrase: string; missingChars: string[] }> } {
  let valid = 0;
  let invalid = 0;
  const invalidPhrases: Array<{ phrase: string; missingChars: string[] }> = [];
  
  for (const phrase of phrases) {
    const result = checkPhraseInCodeTable(phrase, codeTableChars);
    if (result.valid) {
      valid++;
    } else {
      invalid++;
      invalidPhrases.push({
        phrase,
        missingChars: result.missingChars,
      });
    }
  }
  
  return {
    total: phrases.length,
    valid,
    invalid,
    invalidPhrases,
  };
}

