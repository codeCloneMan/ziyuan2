// 覆盖率计算
// ========================================

export interface CoverageResult {
  covered: number;
  total: number;
  percentage: number;
  missing: string[];
}

/** 计算字符集覆盖率 */
export function calculateCoverage(chars: string[], standard: string): CoverageResult {
  const sourceSet = new Set(chars);
  let totalSet: string[];

  switch (standard) {
    case 'gb2312':
      totalSet = gb2312All;
      break;
    case 'gbk':
      totalSet = gbk;
      break;
    case 'top500':
      totalSet = top500Chars;
      break;
    case 'top1000':
      totalSet = top1000Chars;
      break;
    case 'top3000':
      totalSet = top3000Chars;
      break;
    case 'tonggui':
      totalSet = tongguiAll;
      break;
    default:
      totalSet = top3000Chars;
  }

  const total = totalSet.length;
  const missing: string[] = [];
  let covered = 0;

  for (const ch of totalSet) {
    if (sourceSet.has(ch)) {
      covered++;
    } else {
      missing.push(ch);
    }
  }

  const percentage = total > 0
    ? Math.min(100, Math.max(0, (covered / total) * 100))
    : 0;

  return { covered, total, percentage, missing };
}

