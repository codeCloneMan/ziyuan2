export function isCharInSet(char: string, setName: string): boolean {
  const set = charSets[setName];
  if (!set) return false;
  return set.chars.includes(char);
}

export function getMissingChars(
  codeTableChars: string[],
  targetSetName: string
): string[] {
  const targetSet = charSets[targetSetName];
  if (!targetSet) return [];
  
  const codeTableSet = new Set(codeTableChars);
  return targetSet.chars.filter(char => !codeTableSet.has(char));
}

export function calculateCoverage(
  codeTableChars: string[],
  targetSetName: string
): { covered: number; total: number; percentage: number; missing: string[] } {
  const targetSet = charSets[targetSetName];
  if (!targetSet) {
    return { covered: 0, total: 0, percentage: 0, missing: [] };
  }
  
  const codeTableSet = new Set(codeTableChars);
  const covered = targetSet.chars.filter(char => codeTableSet.has(char)).length;
  const missing = targetSet.chars.filter(char => !codeTableSet.has(char));
  
  return {
    covered,
    total: targetSet.count,
    percentage: (covered / targetSet.count) * 100,
    missing,
  };
}
